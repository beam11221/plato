"""
Oracle per-client label distribution for the KL-greedy selector.

Mirrors the role of gpu_tier_sleep.py: loads a pre-generated CSV of
ground-truth label counts and exposes them through a thin API.

Implementation strategy
-----------------------
The CSV is generated by calling PLATO's own ``plato.samplers.dirichlet.Sampler``
for each client.  We do NOT reimplement the sampler — using the real class
guarantees that the oracle counts match actual training data exactly, even if
PLATO's sampler internals change in the future.

The generation is driven by values already loaded into the active Config()
singleton and the live server datasource (both available by the time
KLGreedyServer.configure() calls this module).  There is no separate config
argument to pass or mis-match.

Config fingerprint
------------------
A sidecar <csv_path>.meta.json is written alongside the CSV.  It records
the config parameters that affect the CSV content.  On every server startup,
``ensure_csv_current()`` compares the fingerprint against the active Config().
If any parameter has drifted, the CSV is regenerated automatically.

Public API
----------
ensure_csv_current(datasource, csv_path)
    Call this from KLGreedyServer.configure().  Regenerates the CSV if the
    config fingerprint has changed (or the CSV is missing).  This is the
    primary entry point.

label_counts_for(client_id) -> np.ndarray  shape (K,) int64
    Read the ground-truth label counts for one client.

reset_oracle()
    Reset the module singleton (after CSV regeneration or in tests).

Configuration (TOML)
--------------------
[label_distribution]
csv_path = "/path/to/client_label_distributions.csv"

Falls back to <module_dir>/client_label_distributions.csv when absent.
"""

from __future__ import annotations

import csv
import json
import logging
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

import numpy as np

_MODULE_DIR = Path(__file__).parent


# ---------------------------------------------------------------------------
# Dataclass — one per CSV row, immutable after load
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ClientLabelProfile:
    """Ground-truth label distribution for one client (simulator-only oracle)."""
    client_id: int
    counts: np.ndarray  # shape (K,) int64 — raw class counts


# ---------------------------------------------------------------------------
# Oracle class
# ---------------------------------------------------------------------------

class ClientLabelDistributionOracle:
    """Loads and exposes per-client ground-truth label distributions from CSV."""

    def __init__(self, csv_path: str | Path) -> None:
        self._profiles: dict[int, ClientLabelProfile] = {}
        self._num_classes: int = 0
        self._load(Path(csv_path))

    def _load(self, path: Path) -> None:
        if not path.exists():
            raise FileNotFoundError(
                f"[ClientLabelDist] CSV not found: {path}\n"
                "Call ensure_csv_current() from KLGreedyServer.configure() "
                "to generate it automatically."
            )
        with path.open(newline="") as f:
            reader = csv.DictReader(f)
            class_cols = sorted(
                (k for k in (reader.fieldnames or []) if k.startswith("n_class_")),
                key=lambda c: int(c.split("_")[-1]),
            )
            if not class_cols:
                raise ValueError(
                    f"[ClientLabelDist] No 'n_class_*' columns found in {path}."
                )
            for row in reader:
                cid = int(row["client_id"])
                counts = np.array(
                    [int(row[c]) for c in class_cols], dtype=np.int64
                )
                self._profiles[cid] = ClientLabelProfile(
                    client_id=cid, counts=counts
                )
            self._num_classes = len(class_cols)

        logging.info(
            "[ClientLabelDist] Loaded distributions for %d clients, %d classes from %s.",
            len(self._profiles),
            self._num_classes,
            path,
        )

    @property
    def num_classes(self) -> int:
        return self._num_classes

    def label_counts_for(self, client_id: int) -> np.ndarray:
        """Return the ground-truth label count vector for *client_id*.

        Returns
        -------
        np.ndarray, shape (K,), dtype int64
        """
        profile = self._profiles.get(client_id)
        if profile is None:
            raise KeyError(
                f"[ClientLabelDist] client_id={client_id} not found in CSV."
            )
        return profile.counts


# ---------------------------------------------------------------------------
# Module-level singleton — lazy-initialised on first label_counts_for() call
# ---------------------------------------------------------------------------

_oracle: Optional[ClientLabelDistributionOracle] = None


def _resolve_csv_path() -> Path:
    """Read CSV path from TOML [label_distribution] section, fall back to module dir."""
    try:
        from plato.config import Config  # noqa: PLC0415
        lbd_cfg = getattr(Config().config, "label_distribution", None)
        if lbd_cfg is not None:
            raw = getattr(lbd_cfg, "csv_path", None)
            if raw:
                return Path(os.path.expanduser(str(raw)))
    except Exception:  # noqa: BLE001
        pass
    return _MODULE_DIR / "client_label_distributions.csv"


def get_oracle() -> ClientLabelDistributionOracle:
    """Return the module-level singleton, initialising it on first call."""
    global _oracle
    if _oracle is None:
        csv_path = _resolve_csv_path()
        _oracle = ClientLabelDistributionOracle(csv_path)
    return _oracle


def reset_oracle() -> None:
    """Reset the singleton (called after CSV regeneration so the next
    get_oracle() call re-reads the freshly written file)."""
    global _oracle
    _oracle = None


def label_counts_for(client_id: int) -> np.ndarray:
    """Convenience wrapper — returns the label count array for *client_id*."""
    return get_oracle().label_counts_for(client_id)


# ---------------------------------------------------------------------------
# Config fingerprint — detects stale CSVs
# ---------------------------------------------------------------------------

def _active_fingerprint() -> dict[str, Any]:
    """
    Return a dict of the config values that determine the CSV content.
    Called from KLGreedyServer.configure() against the live Config() singleton
    — the same object that drives the training run.
    """
    from plato.config import Config  # noqa: PLC0415
    data = Config().data
    clients = Config().clients

    fp: dict[str, Any] = {
        "total_clients": int(clients.total_clients),
        "partition_size": int(data.partition_size),
        "concentration": float(getattr(data, "concentration", 1.0)),
        "random_seed": int(getattr(data, "random_seed", 0)),
        "dataset_name": str(getattr(data, "dataset_name", "CIFAR10")),
        "partition_dist": None,
    }
    if hasattr(data, "partition_distribution"):
        pd = data.partition_distribution
        dist_type = str(getattr(pd, "distribution", "")).lower()
        if dist_type == "uniform":
            fp["partition_dist"] = {
                "distribution": "uniform",
                "low": float(pd.low),
                "high": float(pd.high),
            }
        elif dist_type == "normal":
            fp["partition_dist"] = {
                "distribution": "normal",
                "mean": float(pd.mean),
                "std": float(pd.high),  # PLATO uses pd.high as std for normal
            }
    return fp


def _meta_path(csv_path: Path) -> Path:
    return csv_path.with_suffix(csv_path.suffix + ".meta.json")


def _read_fingerprint(csv_path: Path) -> Optional[dict[str, Any]]:
    meta = _meta_path(csv_path)
    if not meta.exists():
        return None
    try:
        return json.loads(meta.read_text())
    except Exception:  # noqa: BLE001
        return None


def _write_fingerprint(csv_path: Path, fp: dict[str, Any]) -> None:
    _meta_path(csv_path).write_text(json.dumps(fp, indent=2))


def _fingerprint_matches(csv_path: Path) -> bool:
    """Return True iff the sidecar fingerprint matches the active Config()."""
    stored = _read_fingerprint(csv_path)
    if stored is None:
        return False
    current = _active_fingerprint()
    if stored != current:
        logging.info(
            "[ClientLabelDist] Config drift detected.\n"
            "  stored : %s\n"
            "  current: %s",
            json.dumps(stored, indent=2),
            json.dumps(current, indent=2),
        )
        return False
    return True


# ---------------------------------------------------------------------------
# CSV generator — uses PLATO's dirichlet.Sampler directly
# ---------------------------------------------------------------------------

def _generate_csv(
    csv_path: Path,
    datasource: Any,
) -> None:
    """
    Build the label-distribution CSV by calling PLATO's dirichlet.Sampler
    for every client.

    We use PLATO's own sampler — not a reimplementation — so the oracle
    counts are guaranteed to match the actual training data exactly.  The
    sampler reads concentration, random_seed, partition_size, and
    partition_distribution directly from the live Config() singleton.

    The numpy global RNG state is saved and restored around the loop so
    that generating the oracle does not disturb the rest of the training run.

    Parameters
    ----------
    csv_path  : destination CSV path
    datasource: the server's live datasource (already initialised)
    """
    from plato.config import Config  # noqa: PLC0415
    from plato.samplers import dirichlet as dirichlet_sampler

    total_clients = int(Config().clients.total_clients)

    # Infer number of classes from the datasource
    classes = datasource.classes()
    num_classes = len(classes)
    targets = np.array(datasource.targets())

    logging.info(
        "[ClientLabelDist] Generating CSV for %d clients, %d classes → %s",
        total_clients,
        num_classes,
        csv_path,
    )

    csv_path.parent.mkdir(parents=True, exist_ok=True)
    class_cols = [f"n_class_{k}" for k in range(num_classes)]

    # Save numpy state so the generator loop does not pollute the global RNG
    # used elsewhere in PLATO (e.g. for training reproducibility).
    saved_np_state = np.random.get_state()

    try:
        with csv_path.open("w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["client_id"] + class_cols)

            for cid in range(1, total_clients + 1):
                sampler = dirichlet_sampler.Sampler(
                    datasource, client_id=cid, testing=False
                )
                sub_sampler = sampler.get()          # SubsetRandomSampler
                indices = list(sub_sampler.indices)  # WeightedRandomSampler result
                counts = np.bincount(
                    targets[indices], minlength=num_classes
                ).astype(np.int64)
                writer.writerow([cid] + counts.tolist())
    finally:
        np.random.set_state(saved_np_state)

    logging.info("[ClientLabelDist] CSV written: %s", csv_path)


# ---------------------------------------------------------------------------
# Primary entry point — called from KLGreedyServer.configure()
# ---------------------------------------------------------------------------

def ensure_csv_current(datasource: Any, csv_path: Optional[Path] = None) -> Path:
    """
    Ensure the label-distribution CSV exists and matches the active Config().

    Regenerates automatically if:
      • the CSV file is missing, or
      • the sidecar fingerprint diverges from the current TOML config.

    Always call this from KLGreedyServer.configure() (after super().configure()
    so that datasource is available) before training starts.

    Parameters
    ----------
    datasource : the server's live datasource (already initialised)
    csv_path   : override the path; default reads [label_distribution].csv_path
                 from Config() or falls back to <module_dir>/client_label_distributions.csv

    Returns
    -------
    Path of the (possibly freshly written) CSV.
    """
    if csv_path is None:
        csv_path = _resolve_csv_path()

    needs_regen = not csv_path.exists() or not _fingerprint_matches(csv_path)

    if needs_regen:
        reason = "CSV missing" if not csv_path.exists() else "config changed"
        logging.info(
            "[ClientLabelDist] Regenerating label-distribution CSV (%s).", reason
        )
        _generate_csv(csv_path, datasource)
        _write_fingerprint(csv_path, _active_fingerprint())
        reset_oracle()  # Force singleton reload on next label_counts_for() call
    else:
        logging.info(
            "[ClientLabelDist] CSV is up-to-date, fingerprint matches: %s", csv_path
        )

    return csv_path
