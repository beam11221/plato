"""
Render the 8 Task 4 configs (prompts/STAGE4_verify_scoring.md, Task 4 Step C):
4 arms x 2 upload policies, N=20, C=4, seed 4126, 4,000 rounds, on the
radius-400 trace.

A separate generator from make_sumo_configs.py on purpose, the same reason
gpu_tiers_dataset/fedasync_seeded.py is a separate entry point from
../fedasync_gpu_tier.py: this cell must stay reproducible on its own without
risking the finished, already-documented 8-run n20/n100 experiment
make_sumo_configs.py generates (STATUS.md, RESULTS_n20.md, RESULTS_n100.md).
Nothing under configs/{baseline,gpu,cpu,observed}_n20.toml is touched.

Differences from make_sumo_configs.py's defaults, all required by Step B/C:
    - concentration = 0.8, not that file's 1.0  ("same alpha" as Stage 3)
    - rounds = 4000, not 10000
    - clients_csv / coverage_csv / sleep_csv point at the n20r400 input set
      (input/clients_n20r400.csv, input/coverage_n20r400.csv,
      output/client_sleep_times_n20r400.csv) -- the sleep-time file is a
      byte-identical copy of the Stage 3 N=20 fleet
      (gpu_tiers_dataset/fleets/n20_x10-o7-t3_xa15_p2500_j0p149_s4126/sleep_times.csv),
      not this project's own un-jittered generator, per Step B.
    - a [sumo] upload_policy key, one of "coverage_gated" / "always_accept"
    - its own port block (18510-18545) so it cannot collide with the
      existing n20/n100 configs' ports (18100-19400 range)

Usage:
    python3 make_stage4_task4_configs.py
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
GPU_TIERS_DATASET = HERE.parent / "gpu_tiers_dataset"

ARMS: dict[str, tuple[str | None, str]] = {
    "baseline": (None, "tiers_estimated_15x.csv"),
    "gpu": ("gpu_tops", "tiers_estimated_15x.csv"),
    "cpu": ("cpu", "tiers_cpu.csv"),
    "observed": ("observed", "tiers_estimated_15x.csv"),
}
ARM_PORT_OFFSET = {"baseline": 10, "gpu": 20, "cpu": 30, "observed": 40}
POLICY_PORT_OFFSET = {"coverage_gated": 0, "always_accept": 5}
PORT_BASE = 18500

CELL = "n20r400"
TOTAL_CLIENTS = 20
PER_ROUND = 4  # C = 4
SEED = 4126
ROUNDS = 4000
ANCHOR_SLEEP = 15
PARTITION_SIZE = 2500
CONCENTRATION = 0.8  # Stage 3's alpha, not this project's own default of 1.0

TEMPLATE = """\
# =============================================================================
# Stage 4 Task 4 -- {arm} arm, upload_policy={upload_policy}, {cell} fleet
# =============================================================================
# Generated by sumo_close_loop/make_stage4_task4_configs.py. Do not edit by
# hand; edit the generator so all 8 configs of this cell move together.
#
# N=20, C=4, seed 4126, 4000 rounds, radius-400 trace. sleep_csv is a
# byte-identical copy of the Stage 3 N=20 fleet's sleep_times.csv (Step B).
#
# Run:
#   cd examples/async/fedasync
#   PYTHONPATH=gpu_tiers:.:sumo_close_loop \\
#       python3 sumo_close_loop/sumo_fedasync.py -c {config_path}
# =============================================================================

[general]
base_path = "{base_path}"

[clients]
type = "simple"
total_clients = {total_clients}
per_round = {per_round}
do_test = false

speed_simulation = true
comm_simulation = true
sleep_simulation = true
avg_training_time = 0.0
max_sleep_time = 300

[clients.simulation_distribution]
distribution = "custom"
csv_path = "{sleep_csv}"

[server]
address = "127.0.0.1"
port = {port}
synchronous = false
simulate_wall_time = true
periodic_interval = 1
ping_interval = 30
ping_timeout = 3600

staleness_bound = 25
minimum_clients_aggregated = 1
mixing_hyperparameter = 0.5
adaptive_mixing = true
eval_interval = 10
{polaris_block}
[server.staleness_weighting_function]
type = "polynomial"
a = 0.5

# RSU coverage windows, keyed by client_id, on the radius-400 trace. Written
# by remap_fleet.py; upload_policy is Stage 4 Task 4's addition to
# sumo_server.py (resolve_upload_policy), absent = "coverage_gated".
[sumo]
coverage_csv = "{coverage_csv}"
upload_policy = "{upload_policy}"

[data]
datasource = "Torchvision"
dataset_name = "CIFAR10"
download = true
data_path = "{data_path}"
partition_size = {partition_size}
sampler = "noniid"
concentration = {concentration}
random_seed = {seed}

[trainer]
type = "basic"
rounds = {rounds}
max_concurrency = {per_round}
target_accuracy = 0.9
model_name = "resnet_18"
epochs = 1
batch_size = 64
optimizer = "SGD"

[algorithm]
type = "fedavg"

[parameters]

[parameters.optimizer]
lr = 0.01
momentum = 0.9
weight_decay = 0.0005

[results]
types = "round, elapsed_time, accuracy, train_loss, valid_loss"
record_clients_accuracy = false

[gpu_tier]
tiers_csv   = "{tiers_csv}"
clients_csv = "{clients_csv}"
anchor_tier  = "xavier"
anchor_sleep = {anchor_sleep}
t_round_model = "queue"
"""


def render(arm: str, upload_policy: str, outdir: Path) -> Path:
    predictor, tiers_csv = ARMS[arm]
    name = f"{arm}_{CELL}_{upload_policy}"
    config_path = outdir / f"{name}.toml"
    port = PORT_BASE + ARM_PORT_OFFSET[arm] + POLICY_PORT_OFFSET[upload_policy]

    polaris_block = (
        f'staleness_predictor = "{predictor}"\n'
        "polaris_alpha = 10.0\n"
        "polaris_initial_gradient_bound = 0.5\n"
        "polaris_initial_staleness = 0.01\n"
        if predictor
        else ""
    )

    text = TEMPLATE.format(
        arm=arm,
        cell=CELL,
        upload_policy=upload_policy,
        config_path=config_path.relative_to(HERE.parent),
        base_path=f"./runs/sumo_close_loop/{name}",
        total_clients=TOTAL_CLIENTS,
        per_round=PER_ROUND,
        port=port,
        polaris_block=polaris_block,
        sleep_csv=HERE / "output" / f"client_sleep_times_{CELL}.csv",
        coverage_csv=HERE / "input" / f"coverage_{CELL}.csv",
        clients_csv=HERE / "input" / f"clients_{CELL}.csv",
        tiers_csv=GPU_TIERS_DATASET / "tiers" / tiers_csv,
        data_path=HERE.parent / "data",
        partition_size=PARTITION_SIZE,
        concentration=CONCENTRATION,
        seed=SEED,
        rounds=ROUNDS,
        anchor_sleep=ANCHOR_SLEEP,
    )

    outdir.mkdir(parents=True, exist_ok=True)
    config_path.write_text(text)
    return config_path


def main() -> None:
    outdir = HERE / "configs" / "stage4_task4"
    paths = []
    for arm in ARMS:
        for policy in ("coverage_gated", "always_accept"):
            paths.append(render(arm, policy, outdir))

    # cpu's tiers_cpu.csv must live where the others' tiers_estimated_15x.csv
    # does -- reuse gpu_tiers_dataset/tiers/ if present, else fall back to
    # surgical/input/ (both were confirmed byte-identical to the gpu-arm file
    # in stage4_evidence/sumo_coverage_gating.md's Step B check).
    cpu_tiers = GPU_TIERS_DATASET / "tiers" / "tiers_cpu.csv"
    if not cpu_tiers.exists():
        raise SystemExit(f"missing {cpu_tiers} -- cpu arm cannot be rendered")

    ports = set()
    for p in paths:
        import tomllib

        with p.open("rb") as f:
            port = tomllib.load(f)["server"]["port"]
        if port in ports:
            raise SystemExit(f"port collision at {port} ({p})")
        ports.add(port)

    print(f"Wrote {len(paths)} configs:")
    for p in paths:
        print(f"  {p}")


if __name__ == "__main__":
    main()
