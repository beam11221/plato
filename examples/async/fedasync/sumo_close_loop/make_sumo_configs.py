# RSU coverage windows, keyed by client_id. Written by remap_fleet.py from the
# SUMO trace; it must match the fleet in [gpu_tier] clients_csv.
[sumo]
coverage_csv = "{coverage_csv}"

[data]
datasource = "Torchvision"
dataset_name = "CIFAR10"
