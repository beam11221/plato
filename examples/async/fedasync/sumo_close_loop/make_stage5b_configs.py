"""
Render the 2 Stage 5b configs (prompts/STAGE5B_fix_Ri.md, Step 2).

Identical to Stage 5's `baseline_tier_spec.toml` (make_stage5_configs.py) in
every section except `[sumo]`: same cell (n20r400), same selector
(`baseline`), same `stage0_t_hat` (`tier_spec`) -- only `stage0_r_i` (and,
for `vmax_distance`, `positions_csv` / `rsu_x_m`) varies, so `R_i` is the
only thing that changes between these two runs and Stage 5's own
`baseline_tier_spec` (the `vmax_elapsed` control, NOT re-run here).

Usage:
    python3 make_stage5b_configs.py
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
GPU_TIERS_DATASET = HERE.parent / "gpu_tiers_dataset"

# run_name -> (stage0_r_i, needs positions_csv/rsu_x_m)
RUNS: dict[str, tuple[str, bool]] = {
    "baseline_tier_spec_vmax_distance": ("vmax_distance", True),
    "baseline_tier_spec_oracle_exit": ("oracle_exit", False),
}

# A fresh port block: Stage 5 used 18600-18605, Task 4 used 18500-18545.
PORT_BASE = 18610

CELL = "n20r400"
TOTAL_CLIENTS = 20
PER_ROUND = 4
SEED = 4126
ROUNDS = 4000
ANCHOR_SLEEP = 15
PARTITION_SIZE = 2500
CONCENTRATION = 0.8
UPLOAD_POLICY = "coverage_gated"

COVERAGE_RADIUS_M = 400.0
V_MAX_MPS = 19.444444
RSU_X_M = 600.0

TEMPLATE = """\
# =============================================================================
# Stage 5b -- {run_name}: selector=baseline, stage0_t_hat=tier_spec, \
stage0_r_i={r_i_mode}, {cell} fleet
# =============================================================================
# Generated by sumo_close_loop/make_stage5b_configs.py. Do not edit by hand;
# edit the generator so both configs of this stage move together.
#
# N=20, C=4, seed 4126, 4000 rounds, radius-400 trace, upload_policy={upload_policy}.
# Identical to Stage 5's baseline_tier_spec.toml (the vmax_elapsed control,
# NOT re-run here) in every section except [sumo]'s stage0_r_i and (for
# vmax_distance) positions_csv / rsu_x_m -- see prompts/STAGE5B_fix_Ri.md.
#
# Run:
#   cd examples/async/fedasync
#   PYTHONPATH=gpu_tiers:.:sumo_close_loop \\
#       python3 sumo_close_loop/sumo_fedasync.py -c {config_path}
# =============================================================================

[general]
base_path = "{base_path}"

[clients]
type = "simple"
total_clients = {total_clients}
per_round = {per_round}
do_test = false

speed_simulation = true
comm_simulation = true
sleep_simulation = true
avg_training_time = 0.0
max_sleep_time = 300

[clients.simulation_distribution]
distribution = "custom"
csv_path = "{sleep_csv}"

[server]
address = "127.0.0.1"
port = {port}
synchronous = false
simulate_wall_time = true
periodic_interval = 1
ping_interval = 30
ping_timeout = 3600

staleness_bound = 25
minimum_clients_aggregated = 1
mixing_hyperparameter = 0.5
adaptive_mixing = true
eval_interval = 10

[server.staleness_weighting_function]
type = "polynomial"
a = 0.5

# stage0_r_i is Stage 5b's addition (stage0_filter.py): which R_i formula the
# Stage 0 predicate uses. positions_csv / rsu_x_m are only read when
# stage0_r_i = "vmax_distance".
[sumo]
coverage_csv = "{coverage_csv}"
upload_policy = "{upload_policy}"
stage0_t_hat = "tier_spec"
coverage_radius_m = {radius_m}
v_max_mps = {v_max_mps}
stage0_r_i = "{r_i_mode}"
{position_lines}
[data]
datasource = "Torchvision"
dataset_name = "CIFAR10"
download = true
data_path = "{data_path}"
partition_size = {partition_size}
sampler = "noniid"
concentration = {concentration}
random_seed = {seed}

[trainer]
type = "basic"
rounds = {rounds}
max_concurrency = {per_round}
target_accuracy = 0.9
model_name = "resnet_18"
epochs = 1
batch_size = 64
optimizer = "SGD"

[algorithm]
type = "fedavg"

[parameters]

[parameters.optimizer]
lr = 0.01
momentum = 0.9
weight_decay = 0.0005

[results]
types = "round, elapsed_time, accuracy, train_loss, valid_loss"
record_clients_accuracy = false

[gpu_tier]
tiers_csv   = "{tiers_csv}"
clients_csv = "{clients_csv}"
anchor_tier  = "xavier"
anchor_sleep = {anchor_sleep}
t_round_model = "queue"
"""


def render(run_name: str, outdir: Path, port: int) -> Path:
    r_i_mode, needs_positions = RUNS[run_name]
    config_path = outdir / f"{run_name}.toml"

    position_lines = ""
    if needs_positions:
        position_lines = (
            f'positions_csv = "{HERE / "input" / f"positions_{CELL}.csv"}"\n'
            f"rsu_x_m = {RSU_X_M}\n"
        )

    text = TEMPLATE.format(
        run_name=run_name,
        cell=CELL,
        r_i_mode=r_i_mode,
        upload_policy=UPLOAD_POLICY,
        config_path=config_path.relative_to(HERE.parent),
        base_path=f"./runs/sumo_close_loop/stage5b_{run_name}",
        total_clients=TOTAL_CLIENTS,
        per_round=PER_ROUND,
        port=port,
        sleep_csv=HERE / "output" / f"client_sleep_times_{CELL}.csv",
        coverage_csv=HERE / "input" / f"coverage_{CELL}.csv",
        radius_m=COVERAGE_RADIUS_M,
        v_max_mps=V_MAX_MPS,
        position_lines=position_lines,
        clients_csv=HERE / "input" / f"clients_{CELL}.csv",
        tiers_csv=GPU_TIERS_DATASET / "tiers" / "tiers_estimated_15x.csv",
        data_path=HERE.parent / "data",
        partition_size=PARTITION_SIZE,
        concentration=CONCENTRATION,
        seed=SEED,
        rounds=ROUNDS,
        anchor_sleep=ANCHOR_SLEEP,
    )

    outdir.mkdir(parents=True, exist_ok=True)
    config_path.write_text(text)
    return config_path


def main() -> None:
    outdir = HERE / "configs" / "stage5b"
    paths = []
    for i, run_name in enumerate(RUNS):
        paths.append(render(run_name, outdir, PORT_BASE + i))

    positions_csv = HERE / "input" / f"positions_{CELL}.csv"
    if not positions_csv.exists():
        raise SystemExit(f"missing {positions_csv} -- run remap_positions.py first")

    print(f"Wrote {len(paths)} configs:")
    for p in paths:
        print(f"  {p}")


if __name__ == "__main__":
    main()
