def fleet_rho_cal() -> float:
    """rho_cal for the configured fleet (Prompt D), from the same function the
    entry point re-checks it with at run time."""
    import wen_estimators
    from wen_fleet import Fleet
    from wen_reported import ReportedVehicle

    fleet = Fleet.load(FLEET_DIR, TIERS_CSV)
    reports = [ReportedVehicle(c, 0.0, 0.0, 0.0, fleet.tier(c), fleet.spec(c).tflops_fp16,
                               fleet.spec(c).cpu_ghz, K.partition_size(c))
               for c in fleet.client_ids]
    return wen_estimators.rho_cal(K.FLOPS_FWD_PER_IMAGE, reports)


def parse_cell(cell: str) -> tuple[str, str, bool, str, str, float | None]:
    """SCENARIO:ARM[+stage0][@eps0|@eps1|@prop] -> (..., suffix, rule, epsilon)."""
    scenario, rest = cell.split(":")
    rest, _, suffix = rest.partition("@")
    stage0 = rest.endswith("+stage0")
    arm = rest.removesuffix("+stage0")
    if arm in STUDY2_ARMS:              # the name carries Stage 0 (Prompt I)
        stage0 = arm.endswith("_s0")
    if suffix not in RULE_SUFFIXES:
        raise SystemExit(f"unknown rule suffix @{suffix}")
    rule, epsilon = RULE_SUFFIXES[suffix] or (
        "egreedy", 1.0 if arm in ("random", "random_s0") else 0.2)
    return scenario, arm, stage0, suffix, rule, epsilon


def cell_name(scenario, arm, stage0, seed, tag="", suffix="") -> str:
    stage0 = stage0 and arm not in STUDY2_ARMS
    return (f"{scenario}_{arm}{'_stage0' if stage0 else ''}"
            f"{'_' + suffix if suffix else ''}_s{seed}{tag}")


def render(cell: str, seed: int, rounds: int, port: int, outdir: Path, tag: str) -> Path:
    scenario, arm, stage0, suffix, rule, epsilon = parse_cell(cell)
    name = cell_name(scenario, arm, stage0, seed, tag, suffix)
    rule_lines = f'selection = "{rule}"\n' + (
        f"epsilon = {epsilon}\n" if epsilon is not None else "")
    if arm in ("wen", "wen_fresh") or arm.startswith("wen_fresh_"):
        # Wen's own rule (Prompt E): no epsilon; limits from wen_limits.py (Step 1).
        # The GPU plug-in (Prompt I S2-2b) has its own W5 limits, except with the
        # plug-in switched off (@pluginoff), which is the CPU host again.
        import json
        gpu = arm.startswith("wen_fresh_gpu") and suffix != "pluginoff"
        lim = json.loads((HERE / "evidence" / ("wen_limits_gpu.json" if gpu else
                                                "wen_limits.json")).read_text())
        rule, epsilon = "wen", None
        rule_lines = (f'selection = "wen"\nwen_t_max = {lim["t_max"]!r}\n'
                      f'wen_e_max = {lim["e_max"]!r}\n')
        if suffix == "stale":
            if arm != "wen_fresh":
                raise SystemExit("@stale is a wen_fresh test configuration")
            rule_lines += "wen_fresh_stale_f3_test = true\n"
    if arm in ("polaris", "polaris_s0"):
        # Prompt J: P4's own sampling rule, no epsilon.
        rule, epsilon = "polaris", None
        rule_lines = 'selection = "polaris"\n'
    if suffix == "pluginoff":
        if arm not in STUDY2_ARMS:
            raise SystemExit("@pluginoff is a Study 2 test configuration")
        rule_lines += "study2_plugin_off_test = true\n"
    if arm == "cpu_cal":
        if suffix == "rho1250":
            rule_lines += (f"cpu_rho = {K.CYCLES_PER_BIT_RHO!r}\n"
                           "cpu_rho_test_override = true\n")
        else:
            rule_lines += f"cpu_rho = {fleet_rho_cal()!r}\n"
    path = outdir / f"{name}.toml"
    text = TEMPLATE.format(
        scenario=scenario, arm=arm,
        stage0_tag=(" + Stage 0" if stage0 else "") + (f" / {rule}"
                    + (f" eps={epsilon}" if epsilon is not None else "")),
        rule_lines=rule_lines,
        polaris_alpha=repr(K.POLARIS_ALPHA if arm in ("polaris", "polaris_s0") else 1.0),
        stage0="true" if stage0 else "false", seed=seed, port=port, rounds=rounds,
        config_path=path.relative_to(FEDASYNC),
        base_path=f"./runs/wen_env/{name}", n=K.N_CLIENTS, c=K.CONCURRENCY,
        pl=K.PARTITION_LARGE, ps=K.PARTITION_SMALL, alpha=K.DIRICHLET_ALPHA,
        epochs=K.LOCAL_EPOCHS, flops=K.FLOPS_FWD_PER_IMAGE, eta=K.GPU_EFFICIENCY_ETA,
        sigma=K.JITTER_SIGMA, bw=K.BANDWIDTH_HZ, p=K.TX_POWER_DBM, noise=K.NOISE_DBM,
        phi=K.PATH_LOSS_EXPONENT, rho=K.CYCLES_PER_BIT_RHO, pup=K.UPLOAD_POWER_W,
        emax=K.E_MAX_J, staleness_bound=STALENESS_BOUND, bundle_dir=BUNDLE_DIR,
        fleet_dir=FLEET_DIR, tiers_csv=TIERS_CSV, data_path=DATA_PATH,
    )
    outdir.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def _flatten(d: dict, prefix=()) -> dict:
    """{(section.path, key): value}, e.g. ("server", "port")."""
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(_flatten(v, prefix + (k,)))
        else:
            out[(".".join(prefix), k)] = v
    return out


def validate(paths: list[Path]) -> None:
    flat = [_flatten(tomllib.loads(p.read_text())) for p in paths]
    keys = set().union(*flat)
    differing = {k for k in keys if len({repr(f.get(k)) for f in flat}) > 1}
    unexpected = differing - VARYING
    if unexpected:
        raise SystemExit(f"configs differ in keys outside the arm definition: "
                         f"{sorted(unexpected)}")
    ports = [f[("server", "port")] for f in flat]
    if len(set(ports)) != len(ports):
        raise SystemExit("port collision")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--smoke", action="store_true")
    parser.add_argument("--resmoke", action="store_true", help="Prompt C Step 3")
    parser.add_argument("--main", action="store_true", help="Prompt C Step 5 cells")
    parser.add_argument("--cells", nargs="*", default=[])
    parser.add_argument("--seeds", type=int, nargs="*", default=[4126])
    parser.add_argument("--rounds", type=int, default=200)
    parser.add_argument("--tag", default="")
    parser.add_argument("--port-base", type=int, default=PORT_BASE)
    args = parser.parse_args()

    if args.smoke:
        cells, default_tag, sub = list(SMOKE_CELLS), "_smoke", "smoke"
    elif args.resmoke:
        cells, default_tag, sub = list(RESMOKE_CELLS), "_smoke2", "smoke2"
    elif args.main:
        cells, default_tag, sub = list(MAIN_CELLS), "", "main"
    else:
        cells, default_tag, sub = args.cells, "", "runs"
    tag = args.tag or default_tag
    outdir = HERE / "configs" / sub
    paths, port = [], args.port_base
    for seed in args.seeds:
        for cell in cells:
            paths.append(render(cell, seed, args.rounds, port, outdir, tag))
            port += 1
    validate(paths)
    for p in paths:
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
