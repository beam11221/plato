#!/bin/bash
# Verification run for the base.py flush-accounting fix — gpu arm, G=40, 800 rounds.
#
# Before the fix, in-flight concurrency in this exact cell fell 9 -> 4 -> 3 -> 1 by
# round 262 while max_concurrency was 10.  800 rounds is well past that, so if the
# trace stays near 10 the fix holds.  ~30 minutes.
#
# Needs the pod to itself: one arm is ~17.6 GB RSS against a ~29 GB cgroup.
#
#   ./run_verify.sh            # launch (refuses if memory is short)
#   ./run_verify.sh --check    # analyse a finished or in-flight run, launch nothing
#
# Results land in ../../runs/verify/gpu_xa20_gap40, log in ../logs/verify_gpu_xa20_gap40.log.
# The pre-fix run is preserved in ../../runs/gap_sweep_prebugfix/ for comparison.

set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
GPU_TIERS="$(dirname "$HERE")"
EXAMPLE_DIR="$(dirname "$GPU_TIERS")"
REPO_ROOT="$(cd "$EXAMPLE_DIR/../../.." && pwd)"

CONFIG="${CONFIG:-$HERE/gpu_xa20_gap40_verify.toml}"
# Derive the run directory from the config rather than repeating it here: the
# config is regenerated by make_verify_config.py, whose --tag changes this path,
# and a stale copy would analyse the previous verification's results.
RUN_NAME="$(grep -m1 '^base_path' "$CONFIG" | sed 's|.*/||; s|"||g')"
RUN_DIR="$EXAMPLE_DIR/runs/verify/$RUN_NAME"
LOG="$GPU_TIERS/logs/verify_$RUN_NAME.log"
CLEANER="$GPU_TIERS/clean_checkpoints.sh"
PYTHON="${PYTHON:-python3}"
NEEDED_MB=18000

check() {
    if [ ! -f "$LOG" ]; then
        echo "no log at $LOG yet — nothing to check"
        return 0
    fi
    echo "== concurrency (pass: stays near 10; before the fix it hit 1 by round 262) =="
    echo "   run: $RUN_NAME   staleness_bound=$(grep -m1 '^staleness_bound' "$CONFIG" | grep -oE '[0-9]+')"
    "$PYTHON" - "$LOG" <<'PY'
import sys, statistics
from pathlib import Path
sys.path.insert(0, str(Path(sys.argv[1]).parent.parent))
from plot_time_to_accuracy import concurrency_trace

trace, lost = concurrency_trace(Path(sys.argv[1]))
if not trace:
    raise SystemExit("no aggregation events in the log yet")
marks = [m for m in (1, 10, 20, 50, 100, 262, 500, 800) if m <= len(trace)]
print("  in-flight: " + "  ".join(f"r{m}={trace[m - 1]}" for m in marks))
tail = trace[len(trace) // 5:]
print(f"  rounds={len(trace)}  steady-state median={statistics.median(tail):.0f}  "
      f"min={min(tail)}  extra clients merged by flushes={lost}")
print("  VERDICT:", "PASS" if statistics.median(tail) >= 8 else "FAIL — still draining")
PY

    echo
    echo "== refill matches merges (each flush of N should be followed by a selection of N) =="
    grep -oE "Aggregating [0-9]+ clients|selected clients \[[^]]*\]" "$LOG" \
        | awk '/Aggregating/ {n=$2; next}
               {gsub(/[^,]/,"",$0); print n, length($0)+1}' \
        | awk '$1>1 {print "  merged " $1 " -> next selection " $2; seen++}
               END {if (!seen) print "  (no multi-client flush yet)"}'

    echo
    echo "== flush rate (was 3 in 2710 rounds before the fix; watch for it becoming routine) =="
    total=$(grep -c "in aggregation pool" "$LOG")
    multi=$(grep -cE "FedAsync: [2-9][0-9]* client\(s\)" "$LOG")
    echo "  $multi multi-client merges in $total rounds"

    echo
    echo "== sanity =="
    csv=$(ls -t "$RUN_DIR"/results/*.csv 2>/dev/null | head -1)
    [ -n "$csv" ] && "$PYTHON" -c "
import pandas as pd, sys
d = pd.read_csv('$csv'); d = d[d.accuracy > 0]
print(f'  rounds={len(d)}  best accuracy={d.accuracy.max():.4f}  last elapsed={d.elapsed_time.iloc[-1]:.0f}s')
" || echo "  no results CSV yet"
    grep -cE "Traceback|CUDA out of memory" "$LOG" | sed 's/^/  errors in log: /'
}

if [ "${1:-}" = "--check" ]; then
    check
    exit 0
fi

# Memory guard — same reasoning as run_sweep.sh, see HANDOFF § 3.
#
# One difference from run_sweep.sh: cgroup v1 counts page cache in
# usage_in_bytes, and reading the sweep's logs leaves ~10 GB of it behind.  That
# cache is dropped the moment anything needs the memory, so charging it against
# the run refuses a run that would have fitted with 15 GB to spare.  Discount the
# inactive file cache — the part the kernel reclaims first — and leave active
# file cache counted, which stays on the conservative side.
limit=$(cat /sys/fs/cgroup/memory/memory.limit_in_bytes 2>/dev/null || cat /sys/fs/cgroup/memory.max 2>/dev/null)
usage=$(cat /sys/fs/cgroup/memory/memory.usage_in_bytes 2>/dev/null || cat /sys/fs/cgroup/memory.current 2>/dev/null)
reclaimable=$(awk '/^(total_)?inactive_file /{print $2; exit}' /sys/fs/cgroup/memory/memory.stat 2>/dev/null \
              || awk '/^inactive_file /{print $2; exit}' /sys/fs/cgroup/memory.stat 2>/dev/null)
reclaimable="${reclaimable:-0}"
if [ -n "$limit" ] && [ -n "$usage" ] && [ "$limit" != "max" ]; then
    free_mb=$(( (limit - usage + reclaimable) / 1024 / 1024 ))
    echo "cgroup: $(( free_mb / 1024 )) GB free (after discounting $(( reclaimable / 1024 / 1024 / 1024 )) GB"\
         "of reclaimable page cache), this run needs ~$(( NEEDED_MB / 1024 )) GB"
    if [ "$free_mb" -lt "$NEEDED_MB" ]; then
        echo "REFUSING: not enough memory.  Something else is still running — stop it first."
        echo "          (override with NEEDED_MB=0 if you disagree)"
        exit 1
    fi
fi

mkdir -p "$(dirname "$LOG")" "$RUN_DIR"
echo "config : $CONFIG"
echo "log    : $LOG"
echo "results: $RUN_DIR"

"$CLEANER" "$RUN_DIR/checkpoints" 100 5 > "$GPU_TIERS/logs/verify_$RUN_NAME.cleaner.log" 2>&1 &
cleaner_pid=$!
trap 'kill $cleaner_pid 2>/dev/null' EXIT

cd "$EXAMPLE_DIR" || exit 1
PYTHONPATH="$REPO_ROOT:$GPU_TIERS:${PYTHONPATH:-}" \
    "$PYTHON" fedasync_gpu_tier_polaris_vi.py -c "$CONFIG" > "$LOG" 2>&1

echo "run finished (exit $?)"
echo
check
