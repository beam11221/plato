"""
Derive the short verification config from a generated sweep config.

`configs/` is generated output and must never be hand-edited, so the verification
config is derived from it the same way — regenerate this after every
``make_configs.py`` run, or the verification tests a config the sweep no longer
uses.

It changes exactly three keys and asserts it changed each one exactly once, so a
rename upstream fails loudly instead of silently producing a config that differs
from the sweep in ways nobody intended.

    python3 make_verify_config.py                    # from configs/gpu_xa20_gap40.toml
    python3 make_verify_config.py --rounds 400 --tag bound25
"""

from __future__ import annotations

import argparse
from pathlib import Path

_HERE = Path(__file__).parent
_GPU_TIERS = _HERE.parent


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--source", type=Path, default=_GPU_TIERS / "configs" / "gpu_xa20_gap40.toml")
    parser.add_argument("--rounds", type=int, default=800)
    parser.add_argument("--port", type=int, default=8940)
    parser.add_argument(
        "--tag",
        default=None,
        help="suffix for the run directory, so successive verifications do not "
        "overwrite each other (default: none — writes runs/verify/<stem>)",
    )
    parser.add_argument("--out", type=Path, default=None)
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    stem = args.source.stem  # e.g. gpu_xa20_gap40
    run_name = f"{stem}_{args.tag}" if args.tag else stem
    out = args.out or _HERE / f"{stem}_verify.toml"

    changed = {"rounds": 0, "base_path": 0, "port": 0}
    lines = []
    for line in args.source.read_text().splitlines(keepends=True):
        if line.startswith("rounds = "):
            lines.append(f"rounds = {args.rounds}\n"); changed["rounds"] += 1
        elif line.startswith("base_path = "):
            lines.append(f'base_path = "./runs/verify/{run_name}"\n'); changed["base_path"] += 1
        elif line.startswith("port = "):
            lines.append(f"port = {args.port}\n"); changed["port"] += 1
        else:
            lines.append(line)

    missing = [key for key, count in changed.items() if count != 1]
    if missing:
        raise SystemExit(
            f"expected to rewrite each of rounds/base_path/port exactly once, got {changed}. "
            f"Did {args.source.name} change shape?"
        )

    header = (
        f"# VERIFICATION RUN — generated by make_verify_config.py from {args.source.name}.\n"
        f"# Do not hand-edit; regenerate after make_configs.py.\n"
        f"# Identical to the source except rounds ({args.rounds}), base_path and port.\n"
    )
    out.write_text(header + "".join(lines))
    print(f"wrote {out}")
    print(f"  source     {args.source}")
    print(f"  run dir    runs/verify/{run_name}")
    print(f"  rounds     {args.rounds}   port {args.port}")


if __name__ == "__main__":
    main()
