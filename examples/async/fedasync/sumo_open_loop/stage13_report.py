"""
Stage 13 (CIFAR-100 pilot): STAGE13_pilot_report.md + per-run series CSVs.
Spec: gpu_tiers_dataset/prompts/STAGE13_cifar100_pilot.md ("Report").

    python3 stage13_report.py                                  # Stage 13 (4,000 rounds)
    python3 stage13_report.py --stage stage13b --rounds 10000  # Stage 13B

Per run: plateau and accuracy at rounds 1,000 / 2,000 / 3,000 / 4,000; TTA by the
E0 method (11-evaluation centred rolling median, first evaluation >= target; the
same code as analyze_stage7.curve_stats) at 30-80 % with rounds-to-target;
waste and dispatch share per tier; T @ 4,000.  Then the pairs #3/#2, #4/#2,
#5/#3, #2/#1 and the replicate #6/#2 at every target both runs reach.
Runs that have not finished are listed as such.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_stage7 as a7  # noqa: E402
import analyze_stage9 as a9  # noqa: E402

OUT = HERE.parent / "gpu_tiers_dataset" / "stage13_evidence"
TARGETS = (30, 40, 50, 60, 70, 80)
AT = (1000, 2000, 3000, 4000)
RUNS = {1: ("stage13nf_s4126", "baseline_open", "baseline / none"),
        2: ("stage13f_s4126", "baseline_open", "baseline + F"),
        3: ("stage13f_s4126", "gpu_open", "gpu + F"),
        4: ("stage13f_s4126", "observed_open", "observed + F"),
        5: ("stage13f_s4126", "cpu_open", "cpu + F"),
        6: ("stage13rep_s4126", "baseline_open", "baseline + F (replicate of #2)")}
PAIRS = ((3, 2), (4, 2), (5, 3), (2, 1), (6, 2))


def tta_e0(rows, tgt):
    acc = [r["accuracy"] for r in rows]
    sm = a7.rolling_median(acc, a7.SMOOTH_WINDOW)
    hit = next((r for r, v in zip(rows, sm) if v >= tgt / 100.0), None)
    return (hit["sim_time_reconstructed"], hit["round"]) if hit else (None, None)


def analyse(num):
    pfx, cell, label = RUNS[num]
    pfx = pfx.replace("stage13", STAGE, 1)
    if not a9.available(pfx, cell):
        return None
    a7.PREFIX = pfx
    run = a7.parse(cell)
    rows = [r for r in run.curve if r["round"] % a7.EVAL_INTERVAL == 0]
    by_round = {r["round"]: r["accuracy"] for r in rows}
    res = {"label": label, "prefix": pfx, "cell": cell,
           "plateau": a7.curve_stats(run)["plateau"],
           "acc_at": {n: by_round.get(n, by_round.get(max((k for k in by_round if k <= n), default=0))) for n in AT},
           "tta": {t: tta_e0(rows, t) for t in TARGETS},
           "waste": a7.waste(run)["overall"]["wasted_frac"],
           "share": a7.dispatch_share(run)["overall"],
           "T_end": a7.clock_at(run, ROUNDS), "max_round": max(run.clock)}
    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / f"series_{num}_{pfx}_{cell}.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["round", "sim_time_s", "accuracy"])
        for r in rows:
            w.writerow([r["round"], round(r["sim_time_reconstructed"], 3), r["accuracy"]])
    return res


def h(s):
    return f"{s / 3600:.3f} h" if s is not None else "not reached"


STAGE, ROUNDS = "stage13", 4000


def main():
    global STAGE, ROUNDS, AT, OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="stage13")
    ap.add_argument("--rounds", type=int, default=4000)
    a = ap.parse_args()
    STAGE, ROUNDS = a.stage, a.rounds
    AT = tuple(range(1000, ROUNDS + 1, 1000)) if ROUNDS <= 4000 else (1000, 2000, 3000, 4000, 6000, 8000, ROUNDS)
    if STAGE != "stage13":
        OUT = HERE.parent / "gpu_tiers_dataset" / f"{STAGE}_evidence"
    R = {n: analyse(n) for n in RUNS}
    is13 = STAGE == "stage13"
    title = "Stage 13: CIFAR-100 pilot" if is13 else f"Stage 13B: CIFAR-100, {ROUNDS:,} rounds"
    ports = "19701–19706" if is13 else "19721–19726"
    L = [f"# {title} (seed 4126, open population)", "",
         "Generated by `sumo_open_loop/stage13_report.py`. Spec: `prompts/STAGE13_cifar100_pilot.md`"
         + ("." if is13 else f", with every run at {ROUNDS:,} rounds (user request, 2026-10-04); see `STAGE13B_record.md`."), "",
         "## Settings changed from Stage 10 / 11 (open, `p_recur = 0`)", "",
         f"| setting | Stage 10 / 11 | {'Stage 13' if is13 else 'Stage 13B'} | why |", "|---|---|---|---|",
         "| `[data] dataset_name` | CIFAR10 | CIFAR100 | the dataset switch |",
         "| `[parameters.model] num_classes` | (absent, default 10) | 100 | output layer for 100 classes |",
         "| `[trainer] target_accuracy` | 0.9 | 0.99 | unreachable, so no run stops early (spec) |",
         f"| `base_path`, `port` | Stage 10's | new run folders, ports {ports} | separate runs |",
         *([] if is13 else [f"| `[trainer] rounds` | 4000 | {ROUNDS} | Stage 13B: longer training (user request) |"]), "",
         "Everything else is byte-identical to the Stage 10 source configs; `tests/test_stage13_cifar100.py` pins this. "
         f"The only things that can end a run are `rounds = {ROUNDS}` and `target_accuracy`, and the trace (36,000 s) "
         "outlasts every run.", "",
         "**Model note.** The spec says \"ResNet-18 (GroupNorm)\". The model used since Stage 3 is Plato's `resnet_18` "
         "(`plato/models/resnet.py`), which uses **BatchNorm**. Since the spec also says \"unchanged\", it was kept "
         "exactly as before, apart from the output layer.", "",
         "## Per run", "",
         f"| # | run | plateau | acc @ {' / '.join(f'{a // 1000}k' for a in AT)} | waste | share x / o / t | T @ {ROUNDS:,} (s) | last round |",
         "|---|---|---|---|---|---|---|---|"]
    for n, r in R.items():
        if r is None:
            L.append(f"| {n} | {RUNS[n][2]} | not finished | | | | | |")
            continue
        L.append(f"| {n} | {r['label']} | {100 * r['plateau']:.2f}% | "
                 + " / ".join(f"{100 * r['acc_at'][a]:.2f}" for a in AT) + f" | {100 * r['waste']:.2f}% | "
                 + " / ".join(f"{100 * r['share'].get(t, 0):.1f}%" for t in a7.TIERS)
                 + f" | {r['T_end']:.1f} | {r['max_round']} |")
    L += ["", "### TTA (E0: 11-evaluation rolling median, first evaluation ≥ target), sim-time and rounds-to-target", "",
          "| # | run | " + " | ".join(f"{t}%" for t in TARGETS) + " |", "|---|---|" + "---|" * len(TARGETS)]
    for n, r in R.items():
        if r is None:
            continue
        L.append(f"| {n} | {r['label']} | " + " | ".join(
            "not reached" if r["tta"][t][0] is None else f"{h(r['tta'][t][0])} (r {r['tta'][t][1]})" for t in TARGETS) + " |")
    L += ["", "## Pairs: **one seed, not a result**", "",
          "Δ TTA % = (first − second) / second; negative = first run reaches the target sooner. "
          "Only targets reached by both runs are shown.", "",
          "| pair | target | first | second | Δ TTA | Δ rounds-to-target |", "|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        ra, rb = R[a], R[b]
        if ra is None or rb is None:
            L.append(f"| #{a} vs #{b} | — | not finished | | | |")
            continue
        both = [t for t in TARGETS if ra["tta"][t][0] is not None and rb["tta"][t][0] is not None]
        if not both:
            L.append(f"| #{a} vs #{b} | — | no target reached by both | | | |")
        for t in both:
            (ta, na), (tb, nb) = ra["tta"][t], rb["tta"][t]
            L.append(f"| #{a} {ra['label']} vs #{b} {rb['label']} | {t}% | {h(ta)} | {h(tb)} | "
                     f"{100 * (ta - tb) / tb:+.1f}% | {100 * (na - nb) / nb:+.1f}% |")
    L += ["", f"Series (round, sim-time, accuracy at every evaluation): `{OUT.name}/series_<#>_*.csv`.", ""]
    checks = []
    for n, (pfx, cell, _) in RUNS.items():
        f = HERE / "logs" / f"stage13_runcheck.{pfx.replace('stage13', STAGE, 1)}_{cell}.json"
        if f.exists():
            j = json.loads(f.read_text())
            checks.append(f"- #{n}: " + ("sound" if not j["soundness_failures"] else "**" + "; ".join(j["soundness_failures"]) + "**")
                          + f" (conservation {100 * j['conservation_rel_error']:+.2f}%"
                          + (f", fallback {100 * j['fallback_rate']:.1f}%, median pool {j['median_eligible_after_stage0']}"
                             if "fallback_rate" in j else "") + ")")
    L += ["## Soundness checks (plateau rule disabled for this stage)", ""] + (checks or ["- none run yet"]) + [""]
    OUT.mkdir(parents=True, exist_ok=True)
    name = "STAGE13_pilot_report.md" if is13 else f"{STAGE.upper()}_report.md"
    (OUT / name).write_text("\n".join(L) + "\n")
    print(f"wrote {OUT / name}; finished runs: {[n for n, r in R.items() if r]}")


if __name__ == "__main__":
    main()
