"""
Stage 13 (CIFAR-100 pilot): the five Stage 10 open-population methods + one
replicate, run seed 4126.  Spec: gpu_tiers_dataset/prompts/STAGE13_cifar100_pilot.md.

Each config is a Stage 10 Wave A / re-run open config (p_recur = 0, the
p_return = 0 end of Stage 11) with ONLY these changes, each asserted to apply
exactly once:
    dataset_name      "CIFAR10" -> "CIFAR100"
    [parameters.model] num_classes = 100   (the output layer; model unchanged)
    target_accuracy   0.9 -> 0.99          (unreachable: no early stop)
    base_path, port   new run folder / free port (19700-19799)

    run   prefix              source config
    #1    stage13nf_s4126     stage10nf_s4126/baseline_open   baseline / none
    #2    stage13f_s4126      stage10f1_s4126/baseline_open   baseline + F
    #3    stage13f_s4126      stage10f1_s4126/gpu_open        gpu + F
    #4    stage13f_s4126      stage10f1_s4126/observed_open   observed + F
    #5    stage13f_s4126      stage10f1_s4126/cpu_open        cpu + F
    #6    stage13rep_s4126    stage10f1_s4126/baseline_open   replicate of #2

    python3 make_stage13_configs.py [--rounds N --tag preflight]
    python3 make_stage13_configs.py --stage stage13b --rounds 10000
        Stage 13B: the same six runs at 10,000 rounds (prefixes stage13b{nf,f,rep}_s4126,
        ports 19721-19726); only `rounds` additionally changes.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIGS = HERE / "configs"
RUNS = (  # (number, prefix, arm, source dir)
    (1, "stage13nf_s4126", "baseline", "stage10nf_s4126"),
    (2, "stage13f_s4126", "baseline", "stage10f1_s4126"),
    (3, "stage13f_s4126", "gpu", "stage10f1_s4126"),
    (4, "stage13f_s4126", "observed", "stage10f1_s4126"),
    (5, "stage13f_s4126", "cpu", "stage10f1_s4126"),
    (6, "stage13rep_s4126", "baseline", "stage10f1_s4126"),
)
PORT_BASE = {"stage13": 19700, "stage13b": 19720}


def sub_once(text, old, new):
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"expected exactly one {old!r}, found {n}")
    return text.replace(old, new)


def render(num, prefix, arm, source, rounds, tag, stage="stage13"):
    src = (CONFIGS / source / f"{arm}_open.toml").read_text()
    pfx = prefix.replace("stage13", stage, 1) + (f"_{tag}" if tag else "")
    name = f"{arm}_open"
    out = src
    out = re.sub(r'(?m)^base_path = ".*"$', f'base_path = "./runs/sumo_open_loop/{pfx}_{name}"', out, count=1)
    out = re.sub(r"(?m)^port = \d+$", f"port = {PORT_BASE[stage] + 10 * bool(tag) + num}", out, count=1)
    out = sub_once(out, 'dataset_name = "CIFAR10"', 'dataset_name = "CIFAR100"')
    out = sub_once(out, "target_accuracy = 0.9\n", "target_accuracy = 0.99\n")
    out = sub_once(out, "[parameters]\n\n[parameters.optimizer]",
                   "[parameters]\n\n[parameters.model]\nnum_classes = 100\n\n[parameters.optimizer]")
    if rounds != 4000:
        out = sub_once(out, "rounds = 4000\n", f"rounds = {rounds}\n")
    title = "Stage 13 CIFAR-100 pilot" if stage == "stage13" else f"Stage 13B (CIFAR-100, {rounds} rounds)"
    header = (f"# {title}, run #{num}{' (replicate of #2)' if num == 6 else ''}.\n"
              f"# Generated by sumo_open_loop/make_stage13_configs.py from configs/{source}/{name}.toml;\n"
              "# changed: dataset_name, [parameters.model] num_classes, target_accuracy, base_path, port"
              + (", rounds" if rounds != 4000 else "") + ".\n")
    path = CONFIGS / pfx / f"{name}.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + out)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rounds", type=int, default=4000)
    ap.add_argument("--tag", default="")
    ap.add_argument("--stage", choices=list(PORT_BASE), default="stage13")
    a = ap.parse_args()
    for r in RUNS:
        print(render(*r, a.rounds, a.tag, a.stage))


if __name__ == "__main__":
    main()
