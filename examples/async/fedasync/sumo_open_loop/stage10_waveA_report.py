"""
Stage 10: write STAGE10A_report.md when Wave A finishes, then open Wave B.

Called by run_stage10.sh after the 30 Wave A runs.  It runs
analyze_stage10.py --wave A, writes the report (tables + comparisons A-H +
the predictions Wave A can score), and writes logs/stage10_waveB.go ONLY if

  - all 30 Wave A runs are present,
  - no run check stopped or blocked (logs/stage10_runcheck.*.json),
  - the occupancy sequence is identical over every analysed run,
  - baseline/none re-runs are within 3% of 7b/8 in every seed (H).

The report is generated from the numbers; it states each verdict from the
per-seed signs, never from a mean.  It is marked as generated, for review.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_stage10 as a10  # noqa: E402

SEEDS = (4126, 4127, 4128)
LOGS = HERE / "logs"
REPORT = Path(os.environ.get("STAGE10A_REPORT_PATH", a10.EVIDENCE / "STAGE10A_report.md"))
GO_FILE = Path(os.environ.get("STAGE10_GO_PATH", LOGS / "stage10_waveB.go"))


def f(x, d=2, sign=True):
    return "—" if x is None else (f"{x:+.{d}f}" if sign else f"{x:.{d}f}")


def seeds_row(d):
    return " / ".join(f(d.get(s)) + "%" if d.get(s) is not None else "—" for s in SEEDS)


def main() -> int:
    sys.argv = [sys.argv[0], "--wave", "A"] + (
        ["--out", os.environ["STAGE10_ANALYSIS_OUT"]] if "STAGE10_ANALYSIS_OUT" in os.environ else [])
    out = a10.main()
    runs, comps, occ = out["runs"], out["comparisons"], out["occupancy_invariant"]

    wave_a = [f"f1/{s}/{a}_{r}" for s in SEEDS for a in ("baseline", "gpu", "cpu", "observed")
              for r in ("open", "closed")] + [f"nf/{s}/baseline_{r}" for s in SEEDS for r in ("open", "closed")]
    missing = [k for k in wave_a if k not in runs]
    checks = [json.loads(p.read_text()) for p in LOGS.glob("stage10_runcheck.stage10*.json")]
    stops = [(c["prefix"], c["run"], c["stop"]) for c in checks if c.get("stop")]
    # Blocks the user has explicitly accepted (logs/stage10_waveB.accepted, one
    # run name per line; '#' comments give the reason).  An accepted block no
    # longer holds Wave B; every other stop / block still does.
    acc_file = LOGS / "stage10_waveB.accepted"
    accepted = {l.strip() for l in acc_file.read_text().splitlines()
                if l.strip() and not l.startswith("#")} if acc_file.exists() else set()
    all_blocks = [(c["prefix"], c["run"], c["block_wave_b"]) for c in checks if c.get("block_wave_b")]
    blocks = [b for b in all_blocks if f"{b[0]}_{b[1]}" not in accepted]
    accepted_blocks = [b for b in all_blocks if f"{b[0]}_{b[1]}" in accepted]
    accepted_seeds = {(int(b[0][-4:]), b[1].split("_")[1]) for b in accepted_blocks}
    h_ok = all(ok or (int(s), r) in accepted_seeds
               for r in ("open", "closed")
               for s, ok in comps["H"][r]["within_3pct_stop"].items())

    L = []
    L.append("# Stage 10, Wave A report (α = 1 filtered arms, and baseline / none)\n")
    L.append("*Generated by `sumo_open_loop/stage10_waveA_report.py` from "
             "`stage10_analysis_waveA.json` when Wave A finished; for review.*\n")
    L.append(f"Runs analysed: {len(runs)}. Wave A runs missing: {missing or 'none'}. "
             f"Occupancy identical over the common prefix of {occ['common_prefix']} recycles: "
             f"**{occ['identical']}**. Run-check stops: {stops or 'none'}. Wave B blocks: {blocks or 'none'}. "
             f"Blocks accepted by the user (logs/stage10_waveB.accepted): {accepted_blocks or 'none'}.\n")

    L.append("## T @ 4,000 (s)\n")
    L.append("| cell | 4126 | 4127 | 4128 |\n|---|---|---|---|")
    for kind, arms in (("nf", ("baseline",)), ("f1", ("baseline", "gpu", "observed", "cpu"))):
        for arm in arms:
            for r in ("open", "closed"):
                label = f"{arm}{'+F' if kind == 'f1' else ' / none'} {r}"
                vals = [runs.get(f"{kind}/{s}/{arm}_{r}", {}).get("T4000") for s in SEEDS]
                L.append(f"| {label} | " + " | ".join(f(v, 1, False) for v in vals) + " |")

    L.append("\n## Soundness and filter behaviour (filtered runs)\n")
    L.append("| run | cons. err | plateau | fallback | median pool after Stage 0 | rejected | admitted waste x / o / t |")
    L.append("|---|---|---|---|---|---|---|")
    for k, v in sorted(runs.items()):
        if not k.startswith("f1/"):
            continue
        fl, aw = v["filter"], v["admitted_waste_per_tier"]
        L.append(f"| {k} | {100 * v['conservation_rel_error']:.3f}% | {v['plateau']:.4f} | "
                 f"{100 * fl['fallback_rate']:.1f}% | {fl['pool_after_median']} | {100 * fl['reject_rate']:.1f}% | "
                 + " / ".join("—" if aw[t] is None else f"{100 * aw[t]:.1f}%" for t in a10.TIERS) + " |")

    L.append("\n## Comparisons (per seed 4126 / 4127 / 4128; negative = first arm faster)\n")
    L.append("| # | comparison | per seed | verdict |\n|---|---|---|---|")
    L.append(f"| **A** | gpu+F vs baseline+F, open (**headline**) | {seeds_row(comps['A']['per_seed'])} | {comps['A']['verdict_gpu_faster']} |")
    L.append(f"| B | gpu+F vs baseline+F, closed | {seeds_row(comps['B']['per_seed'])} | {comps['B']['verdict_gpu_faster']} |")
    for r in ("open", "closed"):
        c = comps["C"][r]
        L.append(f"| C | gpu+F vs observed+F, {r} | {seeds_row(c['per_seed'])} | {c['verdict_gpu_faster']} "
                 f"(waste gpu − obs, pts: {seeds_row(c['waste_gpu_minus_observed_pts']).replace('%', '')}) |")
    for key, d in comps["D"].items():
        L.append(f"| D | {key} vs baseline / none | {seeds_row(d['per_seed'])} | {d['verdict_faster']} |")
    for r in ("open", "closed"):
        L.append(f"| G | cpu+F vs gpu+F, {r} | {seeds_row(comps['G'][r]['per_seed'])} | cpu slower: {comps['G'][r]['verdict_cpu_slower']} |")
        L.append(f"| H | baseline / none re-run vs 7b/8, {r} | {seeds_row(comps['H'][r]['per_seed'])} | "
                 f"within 2%: {comps['H'][r]['within_2pct']} |")

    L.append("\n### D: waste / mix split vs baseline / none (log-points)\n")
    L.append("| run | total | mix | waste | residual |\n|---|---|---|---|---|")
    for k, v in sorted(runs.items()):
        sp = v.get("vs_baseline_none")
        if sp:
            L.append(f"| {k} | {f(sp['total_pct'])} | {f(sp['mix_pct'])} | {f(sp['waste_pct'])} | {f(sp['residual_pct'])} |")

    L.append("\n### F: additivity: filter-only + scoring-only vs combined (% vs baseline / none)\n")
    L.append("| arm / regime | seed | filter only | scoring only | additive | multiplicative | **measured combined** | filter on vs off |")
    L.append("|---|---|---|---|---|---|---|---|")
    for key, rows in comps["F"].items():
        for s, r in rows.items():
            L.append(f"| {key} | {s} | {f(r['filter_only_pct'])} | {f(r['scoring_only_pct'])} | {f(r['additive_pred_pct'])} | "
                     f"{f(r['multiplicative_pred_pct'])} | **{f(r['combined_pct'])}** | {f(r['vs_filter_off_pct'])} |")

    L.append("\n### Fairness, next to the headline (open)\n")
    L.append("| run | xavier / orin / thor ever dispatched | never dispatched | Jain |\n|---|---|---|---|")
    for s in SEEDS:
        for k in (f"f1/{s}/gpu_open", f"s9/{s}/gpu_open", f"f1/{s}/baseline_open", f"nf/{s}/baseline_open"):
            m = runs.get(k, {}).get("membership")
            if m and "ever_dispatched" in m:
                e = m["ever_dispatched"]
                L.append(f"| {k} | {100 * e['xavier']:.1f} / {100 * e['orin']:.1f} / {100 * e['thor']:.1f}% | "
                         f"{100 * m['fairness']['never_dispatched']:.1f}% | {m['fairness']['jain']:.3f} |")

    L.append("\n### Mechanism: G_i xavier : thor, rounds 2,001–4,000, seen (filtered vs no-filter partner)\n")
    L.append("| arm / regime | 4126 | 4127 | 4128 |\n|---|---|---|---|")
    for arm in ("gpu", "observed", "cpu"):
        for r in ("open", "closed"):
            cells = []
            for s in SEEDS:
                a = runs.get(f"f1/{s}/{arm}_{r}", {}).get("gi") or {}
                b = runs.get(f"s9/{s}/{arm}_{r}", {}).get("gi") or {}
                cells.append(f"{f(a.get('xavier_thor_late_seen'), 2, False)} (no-F {f(b.get('xavier_thor_late_seen'), 2, False)})")
            L.append(f"| {arm} {r} | " + " | ".join(cells) + " |")

    REPORT.write_text("\n".join(L) + "\n")
    ok = not missing and not stops and not blocks and occ["identical"] and h_ok
    if ok:
        GO_FILE.write_text("STAGE10A_report.md written by stage10_waveA_report.py; no stop/block\n")
    print(f"report: {REPORT}; wave B go: {ok} (missing={len(missing)} stops={len(stops)} "
          f"blocks={len(blocks)} occupancy={occ['identical']} H_within_3pct={h_ok})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
